#!/usr/bin/env python3
"""Provision presentation metadata into an unsigned, device-owned store.

This is a packaging step, never an application scanner or an ELF builder. Native
admission remains the only authority for installed-app availability and paths.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import tempfile
from typing import Any

Store = dict[str, bytes]
MAX_APPS = 128
REQUIREMENT_CAPACITIES = (16, 17, 24, 32)
GRANT_CAPACITIES = (16, 17, 18, 24, 32)
MAX_DOCUMENT_BYTES = 65536
MAX_STORE_FILES = 4096
MAX_STORE_BYTES = 64 * 1024 * 1024
PRESENTATION = {"display_name": 95, "icon": 23}
PRESENTATION_FIELDS = (*PRESENTATION, "launcher_visible")
REQUIREMENT = {"capability": "app.catalog", "api": 1}
GRANT = {**REQUIREMENT, "instance_id": 0}
SIGNED_FIELDS = {"signed", "signature", "signatures", "signed_metadata", "signature_algorithm", "signing_key_id"}
MANIFEST_REQUIRED = {"type", "id", "version", "architecture", "file_name", "entry", "requires"}
MANIFEST_OPTIONAL = {"description", "display_name", "icon", "supported_file_types", "runtime_lifecycle", "launcher_visible", "min_firmware_version"}


def require(ok: bool, message: str) -> None:
    if not ok:
        raise ValueError(message)


def document(raw: bytes) -> dict[str, Any]:
    require(type(raw) is bytes and len(raw) <= MAX_DOCUMENT_BYTES, "Metadata document is too large or not bytes")
    def unique(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        value: dict[str, Any] = {}
        for key, item in pairs:
            require(key not in value, "Duplicate JSON field: " + key)
            value[key] = item
        return value
    def bad_constant(value: str) -> None:
        raise ValueError("Non-finite JSON value: " + value)
    try:
        value = json.loads(raw.decode("utf-8"), object_pairs_hook=unique, parse_constant=bad_constant)
    except (UnicodeError, RecursionError) as error:
        raise ValueError("Invalid metadata encoding or nesting") from error
    require(type(value) is dict, "Metadata must be an object")
    return value


def encoded(value: Any) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8")


def keys(value: Any, required: set[str], optional: set[str] = frozenset()) -> None:
    require(type(value) is dict and required <= value.keys() <= required | optional, "Invalid metadata fields")


def text(value: Any, maximum: int, label: str) -> str:
    require(type(value) is str and bool(value), "Invalid " + label)
    try:
        length = len(value.encode("utf-8"))
    except UnicodeError as error:
        raise ValueError("Invalid UTF-8 " + label) from error
    require(length <= maximum and all(ord(c) >= 32 and ord(c) != 127 for c in value), "Invalid " + label)
    return value


def safe_path(value: Any, maximum: int = 192) -> str:
    text(value, maximum, "relative path")
    path = PurePosixPath(value)
    require(not path.is_absolute() and str(path) == value and ".." not in path.parts
            and not any(c in value for c in ("\\", ":")) and value != ".", "Invalid relative path: " + value)
    return value


def identity(value: Any) -> str:
    # RuntimePackages::safeId / Identity::id[64], not catalog display capacity.
    text(value, 63, "application id")
    require(re.fullmatch(r"[a-z0-9](?:[a-z0-9_-]*[a-z0-9])?", value) is not None, "Invalid application id")
    return value


def artifact(value: Any) -> str:
    text(value, 127, "ELF basename")
    require(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*\.elf", value) is not None and ".." not in value,
            "Invalid ELF basename")
    return value


def unsigned(value: Any, depth: int = 0) -> None:
    require(depth <= 16, "Metadata nesting is too deep")
    if isinstance(value, dict):
        require(not SIGNED_FIELDS.intersection(value), "Signed metadata must be regenerated by its signing owner")
        for item in value.values():
            unsigned(item, depth + 1)
    elif isinstance(value, list):
        for item in value:
            unsigned(item, depth + 1)


def presentation(value: dict[str, Any]) -> None:
    for name, maximum in PRESENTATION.items():
        if name in value:
            text(value[name], maximum, name)
    if "launcher_visible" in value:
        require(type(value["launcher_visible"]) is bool, "launcher_visible must be a boolean")


def capability(value: Any, *, grant: bool) -> tuple[str, int, int | None]:
    required = {"capability", "api"} | ({"instance_id"} if grant else set())
    optional = {"file"} if grant else set()
    keys(value, required, optional)
    name = text(value["capability"], 95, "capability")
    api = value["api"]
    require(type(api) is int and 1 <= api <= 0xffffffff, "Invalid capability API")
    instance = value.get("instance_id")
    if grant:
        require(type(instance) is int and 0 <= instance <= 0x7fffffff, "Invalid instance selector")
        require(("file" in value) == (name == "storage.shared-data"), "Invalid shared-data grant")
        if "file" in value:
            file = text(value["file"], 48, "shared-data file")
            require(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", file) is not None, "Invalid shared-data file")
    if name == "app.catalog":
        require(api == 1 and (not grant or instance == 0), "Invalid app.catalog authority")
    return name, api, instance


def validate_store(store: Store) -> None:
    require(type(store) is dict and len(store) <= MAX_STORE_FILES, "Invalid or oversized store")
    total = 0
    for name, raw in store.items():
        safe_path(name)
        require(type(raw) is bytes, "Store values must be bytes")
        total += len(raw)
        require(total <= MAX_STORE_BYTES, "Store byte bound exceeded")
        for parent in PurePosixPath(name).parents:
            require(str(parent) not in store, "Store file/directory path collision")
        require(not name.lower().endswith((".sig", ".signature")) and PurePosixPath(name).name.lower() not in
                {"signature.json", "signatures.json", "signed.json"}, "Signed metadata sidecar must be regenerated by its signing owner")


def stage(store: Store, profile: dict[str, Any], *, requirement_capacity: int,
          grant_capacity: int) -> tuple[Store, dict[str, Any]]:
    """Apply selected metadata without adding apps, removing grants or editing ELFs."""
    require(type(requirement_capacity) is int and requirement_capacity in REQUIREMENT_CAPACITIES, "Invalid native requirement capacity")
    require(type(grant_capacity) is int and grant_capacity in GRANT_CAPACITIES, "Invalid native grant capacity")
    validate_store(store)
    keys(profile, {"schema", "entries", "consumers"})
    require(type(profile["schema"]) is int and profile["schema"] == 1, "Unsupported catalog metadata schema")
    require(type(profile["entries"]) is list and len(profile["entries"]) <= MAX_APPS, "Invalid presentation entry count")
    require(type(profile["consumers"]) is list and len(profile["consumers"]) <= MAX_APPS, "Invalid consumer count")
    selections: dict[str, dict[str, Any]] = {}
    selected_ids: set[str] = set()
    for item in profile["entries"]:
        keys(item, {"manifest", "id"}, set(PRESENTATION) | {"launcher_visible"})
        name = safe_path(item["manifest"])
        require(name.endswith(".json"), "Manifest path must end in .json")
        app_id = identity(item["id"])
        presentation(item)
        require(name not in selections and app_id not in selected_ids, "Duplicate presentation identity/path")
        selections[name] = item
        selected_ids.add(app_id)
    consumers: set[str] = set()
    for name in profile["consumers"]:
        name = safe_path(name)
        require(name not in consumers, "Duplicate consumer path")
        consumers.add(name)
    require("boot.json" in store, "Missing boot.json")
    boot = document(store["boot.json"])
    unsigned(boot)
    original_boot = copy.deepcopy(boot)
    policies = boot.get("app_capabilities")
    require(type(policies) is list and len(policies) <= MAX_APPS, "Invalid application inventory")
    manifests: dict[str, dict[str, Any]] = {}
    ids: dict[str, str] = {}
    paths: set[str] = set()
    for policy in policies:
        require(type(policy) is dict and {"manifest", "grants"} <= policy.keys(), "Invalid application policy")
        name = safe_path(policy["manifest"])
        require(name.endswith(".json") and name != "boot.json" and name in store, "Missing or invalid application manifest")
        require(name not in manifests, "Duplicate application manifest path")
        manifest = document(store[name])
        unsigned(manifest)
        keys(manifest, MANIFEST_REQUIRED, MANIFEST_OPTIONAL)
        require(manifest["type"] == "application" and manifest["architecture"] == "xtensa-esp32s3"
                and manifest["entry"] == "app_main", "Invalid application manifest")
        app_id = identity(manifest["id"])
        version = text(manifest["version"], 31, "application version")
        require(re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version) is not None
                and all(int(part) <= 0xffffffff for part in version.split(".")), "Invalid application version")
        filename = artifact(manifest["file_name"])
        # Preserve the declared launch identity, including legacy long paths.
        # The final native admission check owns platform path-length limits.
        launch_path = (PurePosixPath(name).parent / filename).as_posix()
        require(app_id not in ids and launch_path not in paths, "Duplicate application identity/ELF path")
        ids[app_id] = name
        paths.add(launch_path)
        # Legacy descriptive values are left for the native display fallback.
        # Visibility controls membership and must always be explicitly boolean.
        if "launcher_visible" in manifest:
            require(type(manifest["launcher_visible"]) is bool, "launcher_visible must be a boolean")
        requirements, grants = manifest["requires"], policy["grants"]
        require(type(requirements) is list and len(requirements) <= requirement_capacity, "Native requirement capacity exceeded")
        require(type(grants) is list and len(grants) <= grant_capacity, "Native grant capacity exceeded")
        req_keys = [capability(value, grant=False)[:2] for value in requirements]
        grant_keys = [capability(value, grant=True) for value in grants]
        require(len(set(req_keys)) == len(req_keys), "Duplicate application requirement")
        require(len(set(grant_keys)) == len(grant_keys), "Duplicate application grant")
        manifests[name] = manifest
    require(consumers <= manifests.keys(), "Unknown catalog consumer: " + ", ".join(sorted(consumers - manifests.keys())))
    skipped: list[str] = []
    for name, item in selections.items():
        if name not in manifests:
            require(item["id"] not in ids and name not in store, "Presentation identity/path conflicts with installed store")
            skipped.append(name)
            continue
        require(manifests[name]["id"] == item["id"], "Presentation application identity mismatch")
        for field in PRESENTATION_FIELDS:
            if field in item:
                manifests[name][field] = item[field]
    for policy in policies:
        name = policy["manifest"]
        if name not in consumers:
            continue
        requirements = manifests[name]["requires"]
        if REQUIREMENT not in requirements:
            require(len(requirements) < requirement_capacity, "Native requirement capacity exceeded")
            requirements.append(dict(REQUIREMENT))
        if GRANT not in policy["grants"]:
            require(len(policy["grants"]) < grant_capacity, "Native grant capacity exceeded")
            policy["grants"].append(dict(GRANT))
    out = dict(store)
    for name, value in {**manifests, "boot.json": boot}.items():
        if value != document(store[name]):
            raw = encoded(value)
            require(len(raw) <= MAX_DOCUMENT_BYTES, "Staged metadata document is too large")
            out[name] = raw
    # Defense in depth: compare exact permitted edits, including all opaque
    # policy fields, namespace selectors and shared-file selections.
    for old, new in zip(original_boot["app_capabilities"], policies):
        expected = copy.deepcopy(old)
        if old["manifest"] in consumers and GRANT not in expected["grants"]:
            expected["grants"].append(dict(GRANT))
        require(new == expected, "Existing policy changed")
    expected_boot = copy.deepcopy(original_boot)
    expected_boot["app_capabilities"] = policies
    require(boot == expected_boot, "Unrelated boot metadata changed")
    changed = sorted(name for name in store if store[name] != out[name])
    require(set(out) == set(store) and set(changed) <= set(manifests) | {"boot.json"}, "Store payload/inventory changed")
    for name in manifests:
        expected = document(store[name])
        for field in PRESENTATION_FIELDS:
            if field in selections.get(name, {}):
                expected[field] = selections[name][field]
        if name in consumers and REQUIREMENT not in expected["requires"]:
            expected["requires"].append(dict(REQUIREMENT))
        require(manifests[name] == expected, "Unrelated manifest metadata changed")
    elf_hashes = {name: hashlib.sha256(raw).hexdigest() for name, raw in sorted(store.items()) if name.endswith(".elf")}
    report = {"schema": 1, "flashable": False, "requires_device_assembly": True,
              "requires_cohort_rebind": "cohort.json" in store, "applications": len(policies),
              "consumers": sorted(consumers), "skipped_absent_entries": sorted(skipped),
              "changed_files": changed, "added_files": [], "unchanged_files": len(store) - len(changed),
              "requirement_capacity": requirement_capacity, "grant_capacity": grant_capacity,
              "elf_sha256": elf_hashes}
    return out, report


def read_store(root: Path) -> Store:
    require(root.is_dir() and not root.is_symlink(), "Store directory is missing or linked")
    store: Store = {}
    total = 0
    for path in root.rglob("*"):
        require(not path.is_symlink(), "Linked store input")
        if path.is_dir():
            continue
        require(path.is_file(), "Store contains a non-regular file")
        require(len(store) < MAX_STORE_FILES and total + path.stat().st_size <= MAX_STORE_BYTES, "Store bound exceeded")
        name = safe_path(path.relative_to(root).as_posix())
        store[name] = path.read_bytes()
        total += len(store[name])
    validate_store(store)
    return store


def write_new_store(path: Path, store: Store) -> None:
    validate_store(store)
    require(not path.exists() and not path.is_symlink(), "Output already exists; input is never overwritten")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = Path(tempfile.mkdtemp(prefix=".catalog-stage-", dir=path.parent))
    try:
        for name, raw in store.items():
            target = temporary / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
        require(not path.exists() and not path.is_symlink(), "Output appeared during staging")
        temporary.rename(path)
    finally:
        if temporary.exists():
            shutil.rmtree(temporary)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("store", "profile", "output"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--requirement-capacity", type=int, choices=REQUIREMENT_CAPACITIES, required=True)
    parser.add_argument("--grant-capacity", type=int, choices=GRANT_CAPACITIES, required=True)
    args = parser.parse_args()
    try:
        require(args.store.resolve() not in args.output.resolve().parents and args.store.resolve() != args.output.resolve(),
                "Output must be outside the input store")
        require(args.profile.is_file() and not args.profile.is_symlink(), "Profile is missing or linked")
        require(args.profile.stat().st_size <= MAX_DOCUMENT_BYTES, "Profile document is too large")
        staged, report = stage(read_store(args.store), document(args.profile.read_bytes()),
                               requirement_capacity=args.requirement_capacity, grant_capacity=args.grant_capacity)
        write_new_store(args.output, staged)
    except (ValueError, OSError) as error:
        parser.exit(2, "catalog metadata staging: " + str(error) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
