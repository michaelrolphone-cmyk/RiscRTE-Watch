"""Rasterize the existing OFL Share Tech Mono font for literal crash reports."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[1]
f=ImageFont.truetype(str(root/'apps/clock/nova/fonts/ShareTechMono-Regular.ttf'),13)
rows=[]
for c in range(32,127):
 im=Image.new('L',(8,16));ImageDraw.Draw(im).text((0,0),chr(c),font=f,fill=255)
 rows.append([sum((1<<x) for x in range(8) if im.getpixel((x,y))>=96) for y in range(16)])
(root/'apps/clock/nova/crash_font.inc').write_text('/* Share Tech Mono, OFL; generated by scripts/generate_crash_font.py. */\nstatic const uint8_t crash_font[95][16]={\n'+''.join(' {'+','.join(map(str,r))+'},\n' for r in rows)+'};\n')
